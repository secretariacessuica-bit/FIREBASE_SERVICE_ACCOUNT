let currentLang = localStorage.getItem("lima_lang") || "pt";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("lima_lang", lang);
  applyTranslations();
  
  // Custom reload function for dynamic content if any
  if (typeof updateDynamicTranslations === 'function') {
    updateDynamicTranslations();
  }
}

function toggleLanguage() {
  const newLang = currentLang === "pt" ? "fr" : "pt";
  setLanguage(newLang);
}

function t(key) {
  return translations[currentLang][key] || key;
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[currentLang][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translations[currentLang][key];
      } else {
        // Keep child elements (like icons) intact if needed, or simply replace textContent
        // Assuming data-i18n sets the primary text. If there are icons, we should use innerHTML carefully,
        // but it's safer to wrap text in a <span>.
        if (el.querySelector('.i18n-text')) {
           el.querySelector('.i18n-text').textContent = translations[currentLang][key];
        } else {
           el.textContent = translations[currentLang][key];
        }
      }
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[currentLang][key]) {
      el.placeholder = translations[currentLang][key];
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});
